// Dense symmetric eigendecomposition: Householder reduction to tridiagonal
// form, then the implicit QL method (the classic tred2 / tql2 pair). Used
// whole for small graphs, and for the Lanczos tridiagonal (lanczos.ts).

// Eigenvalues of the symmetric tridiagonal matrix with diagonal `d` and
// off-diagonal `e` (e[i] joins i and i + 1; e has d.length - 1 entries),
// ascending, written into d. Each array in `rows` is a row of the eigenvector
// matrix to carry along (start it as a row of the identity); the result's
// column k belongs to the k-th eigenvalue. Carrying only the rows that are
// needed keeps a Lanczos convergence check cheap.
export function tridiagonalEigen(d: Float64Array, offDiag: Float64Array, rows: Float64Array[]): void {
  const n = d.length;
  const e = new Float64Array(n);
  e.set(offDiag.subarray(0, n - 1));
  const eps = 2 ** -52;
  let f = 0;
  let tst1 = 0;
  for (let l = 0; l < n; l++) {
    tst1 = Math.max(tst1, Math.abs(d[l]) + Math.abs(e[l]));
    let m = l;
    while (m < n) {
      if (Math.abs(e[m]) <= eps * tst1) break;
      m++;
    }
    if (m > l) {
      let iter = 0;
      do {
        if (++iter > 100) throw new Error("tridiagonalEigen: no convergence");
        let g = d[l];
        let p = (d[l + 1] - g) / (2 * e[l]);
        let r = Math.hypot(p, 1);
        if (p < 0) r = -r;
        d[l] = e[l] / (p + r);
        d[l + 1] = e[l] * (p + r);
        const dl1 = d[l + 1];
        let h = g - d[l];
        for (let i = l + 2; i < n; i++) d[i] -= h;
        f += h;
        p = d[m];
        let c = 1;
        let c2 = c;
        let c3 = c;
        const el1 = e[l + 1];
        let s = 0;
        let s2 = 0;
        for (let i = m - 1; i >= l; i--) {
          c3 = c2;
          c2 = c;
          s2 = s;
          g = c * e[i];
          h = c * p;
          r = Math.hypot(p, e[i]);
          e[i + 1] = s * r;
          s = e[i] / r;
          c = p / r;
          p = c * d[i] - s * g;
          d[i + 1] = h + s * (c * g + s * d[i]);
          for (const row of rows) {
            h = row[i + 1];
            row[i + 1] = s * row[i] + c * h;
            row[i] = c * row[i] - s * h;
          }
        }
        p = (-s * s2 * c3 * el1 * e[l]) / dl1;
        e[l] = s * p;
        d[l] = c * p;
      } while (Math.abs(e[l]) > eps * tst1);
    }
    d[l] += f;
    e[l] = 0;
  }
  // Ascending, columns with them.
  for (let i = 0; i < n - 1; i++) {
    let k = i;
    let p = d[i];
    for (let j = i + 1; j < n; j++) {
      if (d[j] < p) {
        k = j;
        p = d[j];
      }
    }
    if (k !== i) {
      d[k] = d[i];
      d[i] = p;
      for (const row of rows) {
        const t = row[i];
        row[i] = row[k];
        row[k] = t;
      }
    }
  }
}

// Every eigenpair of the symmetric matrix A (rows), ascending: values, and
// vectors[k] the unit eigenvector of values[k].
export function symmetricEigen(A: Float64Array[]): { values: Float64Array; vectors: Float64Array[] } {
  const n = A.length;
  const V = A.map((r) => Float64Array.from(r));
  const d = new Float64Array(n);
  const e = new Float64Array(n);
  // Householder reduction to tridiagonal form (tred2), accumulating the
  // transformations in V.
  for (let j = 0; j < n; j++) d[j] = V[n - 1][j];
  for (let i = n - 1; i > 0; i--) {
    let scale = 0;
    let h = 0;
    for (let k = 0; k < i; k++) scale += Math.abs(d[k]);
    if (scale === 0) {
      e[i] = d[i - 1];
      for (let j = 0; j < i; j++) {
        d[j] = V[i - 1][j];
        V[i][j] = 0;
        V[j][i] = 0;
      }
    } else {
      for (let k = 0; k < i; k++) {
        d[k] /= scale;
        h += d[k] * d[k];
      }
      let f = d[i - 1];
      let g = Math.sqrt(h);
      if (f > 0) g = -g;
      e[i] = scale * g;
      h -= f * g;
      d[i - 1] = f - g;
      for (let j = 0; j < i; j++) e[j] = 0;
      for (let j = 0; j < i; j++) {
        f = d[j];
        V[j][i] = f;
        g = e[j] + V[j][j] * f;
        for (let k = j + 1; k <= i - 1; k++) {
          g += V[k][j] * d[k];
          e[k] += V[k][j] * f;
        }
        e[j] = g;
      }
      f = 0;
      for (let j = 0; j < i; j++) {
        e[j] /= h;
        f += e[j] * d[j];
      }
      const hh = f / (h + h);
      for (let j = 0; j < i; j++) e[j] -= hh * d[j];
      for (let j = 0; j < i; j++) {
        f = d[j];
        g = e[j];
        for (let k = j; k <= i - 1; k++) V[k][j] -= f * e[k] + g * d[k];
        d[j] = V[i - 1][j];
        V[i][j] = 0;
      }
    }
    d[i] = h;
  }
  for (let i = 0; i < n - 1; i++) {
    V[n - 1][i] = V[i][i];
    V[i][i] = 1;
    const h = d[i + 1];
    if (h !== 0) {
      for (let k = 0; k <= i; k++) d[k] = V[k][i + 1] / h;
      for (let j = 0; j <= i; j++) {
        let g = 0;
        for (let k = 0; k <= i; k++) g += V[k][i + 1] * V[k][j];
        for (let k = 0; k <= i; k++) V[k][j] -= g * d[k];
      }
    }
    for (let k = 0; k <= i; k++) V[k][i + 1] = 0;
  }
  for (let j = 0; j < n; j++) {
    d[j] = V[n - 1][j];
    V[n - 1][j] = 0;
  }
  V[n - 1][n - 1] = 1;
  // tql2 wants e shifted: e[i] joins i and i + 1.
  const off = new Float64Array(Math.max(0, n - 1));
  for (let i = 1; i < n; i++) off[i - 1] = e[i];
  tridiagonalEigen(d, off, V);
  const vectors = Array.from({ length: n }, (_, k) => {
    const v = new Float64Array(n);
    for (let i = 0; i < n; i++) v[i] = V[i][k];
    return v;
  });
  return { values: d, vectors };
}
